export const testimonials = []

export const DEMO_MARKERS = ['פארק רזידנס', 'גרין הייטס', 'מגדלי המרינה', 'התחדשות מרכז העיר', 'Park Residence', 'Green Heights', 'Marina Towers', 'City Center Renewal']

export function isDemoTestimonial(t) {
  const p = t?.project
  const text = typeof p === 'object' && p ? `${p.he || ''} ${p.en || ''}` : String(p || '')
  return DEMO_MARKERS.some((m) => text.includes(m))
}

export default testimonials
