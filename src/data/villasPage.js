/* ההגדרות של העמוד, כפי שנשמרות ב-site_settings תחת villas_page:
   { header, order: [slug], projects: { [slug]: { hidden, cms, hero, thumbs } } }
   header/hero: ערך תמונה (מחרוזת או אובייקט רספונסיבי). cms: slug של
   הפרויקט במערכת שממנו נמשכות התמונות כשאין override. thumbs: כתובות. */
export function parseVillasSettings(raw) {
  let v = raw
  if (typeof v === 'string') { try { v = JSON.parse(v) } catch { v = null } }
  if (!v || typeof v !== 'object') v = {}
  const projects = (v.projects && typeof v.projects === 'object') ? v.projects : {}
  const known = VILLAS_PROJECTS.map((p) => p.slug)
  const order = Array.isArray(v.order) ? v.order.filter((s) => known.includes(s)) : []
  for (const s of known) if (!order.includes(s)) order.push(s)
  return { header: v.header || '', order, projects }
}

/* הפרויקטים לתצוגה: לפי הסדר שנקבע באדמין, בלי המוסתרים */
export function orderedVillasProjects(settings) {
  const s = parseVillasSettings(settings)
  return s.order
    .map((slug) => VILLAS_PROJECTS.find((p) => p.slug === slug))
    .filter((p) => p && !s.projects[p.slug]?.hidden)
}
