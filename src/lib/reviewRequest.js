/* ============================================================
   בקשת ביקורת מלקוח שסגרנו איתו.

   ביקורות הן המשקל הכבד ביותר בחיפוש מקומי, והדרך היחידה לצבור אותן היא
   לבקש מלקוחות אמיתיים ברגע הנכון. הרגע הנכון הוא סגירת העסקה, ובדיוק אז
   הליד עובר בלוח לשלב "נסגר בהצלחה". במקום לזכור, הלוח מציע את זה.

   ההודעה לא מכתיבה ללקוח מה לכתוב. היא שואלת שאלה שהתשובה הטבעית לה
   כוללת את מה שחשוב לנו: איזה שירות, באיזה יישוב, ומה היה מוחשי בתהליך.
   כך הביקורת נשארת שלו במלואה, וגם עובדת בשבילנו.
   ============================================================ */

const TEMPLATES = [
  {
    match: /תיווך|מכירה|רכישה|קונה|מוכר/,
    body: (n) => `היי ${n}, מזל טוב על הנכס. אם תוכל/י לשתף בגוגל כמה זמן לקח התהליך ואיך ליווינו אותך במשא ומתן ובחתימה, זה שווה המון למי שמחפש עכשיו נכס באזור.`,
  },
  {
    match: /פיקוח|מפקח|בדק/,
    body: (n) => `היי ${n}, תודה על האמון בליווי הפיקוח. אם תוכל/י לכתוב בגוגל מה הפיקוח שלנו מצא או מנע בפרויקט שלך, זו בדיוק ההמלצה שתעזור למי שמתלבט אם לוותר על פיקוח.`,
  },
  {
    match: /ביצוע|בנייה|בניה|קבלן/,
    body: (n) => `היי ${n}, סיימנו את הביצוע ואנחנו גאים בתוצאה. אם יש לך דקה, נשמח שתכתוב/תכתבי בגוגל איך התנהל אתר הבנייה: עמידה בלוחות זמנים, סדר באתר ואיכות הגימור.`,
  },
  {
    match: /מנטור|ליווי יזמ|יזמים צעירים/,
    body: (n) => `היי ${n}, מקווים שהכלים מהליווי משרתים אותך בשטח. אם תוכל/י לכתוב בגוגל מה השתנה אצלך בפועל אחרי הליווי, ולו דבר אחד קונקרטי, זה יעזור ליזם שמתלבט אם זה בשבילו.`,
  },
  {
    match: /יזמות|קרקע|שותפ/,
    body: (n) => `היי ${n}, תודה על השותפות בפרויקט. אם תוכל/י לכתוב בגוגל איך היה לעבוד איתנו מצד היזמות: השקיפות בדוחות, עמידה בהתחייבויות וההתנהלות מול הרשויות.`,
  },
]

const PROJECT_BODY = (n) =>
  `היי ${n}, מקווים שאתם מסתדרים מצוין בבית החדש. נשמח לביקורת קצרה בגוגל: מה גרם לכם לבחור דווקא בפרויקט הזה, ואיך הייתה המסירה בפועל.`

const GENERIC_BODY = (n) =>
  `היי ${n}, שמחנו ללוות אתכם. אם תוכלו לשתף בגוגל איך הייתה עבורכם החוויה מול קורקוס גרופ ובאיזה שירות מדובר, זה יעזור מאוד למי שמתלבט.`

/* בוחר את הנוסח לפי מקור הפנייה ולפי נושא הפנייה שנשמר בליד */
export function reviewMessage(lead = {}, reviewUrl = '') {
  const name = String(lead.name || '').trim().split(' ')[0] || 'שלום'
  const topicRaw = lead.project && typeof lead.project === 'object'
    ? (lead.project.he || lead.project.en || '')
    : String(lead.project || '')
  const topic = `${topicRaw} ${lead.message || ''}`

  let body
  if (lead.source === 'project') body = PROJECT_BODY(name)
  else body = (TEMPLATES.find((t) => t.match.test(topic))?.body || GENERIC_BODY)(name)

  return reviewUrl ? `${body}\n\n${reviewUrl}` : body
}

/* קישור וואטסאפ מוכן לשליחה. מחזיר ריק כשאין טלפון תקין. */
export function reviewWaLink(lead = {}, reviewUrl = '') {
  const d = String(lead.phone || '').replace(/\D/g, '')
  if (d.length < 9) return ''
  const intl = d.startsWith('972') ? d : '972' + d.replace(/^0/, '')
  return `https://wa.me/${intl}?text=${encodeURIComponent(reviewMessage(lead, reviewUrl))}`
}
